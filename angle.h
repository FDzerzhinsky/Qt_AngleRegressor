// =============================================================================
// СТРУКТУРА КОНФИГУРАЦИИ НЕЙРОСЕТЕВОЙ МОДЕЛИ 
// =============================================================================
// Содержит все настраиваемые параметры для алгоритмов компьютерного зрения
struct ImageProcessingConfig {
    // Параметры путей и файлов
    std::string ref_image_path = "reference.png"; // Путь к референсному изображению

    // Параметры масштабирования изображений
    double ref_image_scale = 0.5;           // Масштаб референсного изображения

    // Параметры ORB детектора
    int orb_max_features = 500;             // Максимальное количество фич
    double orb_scale_factor = 1.2;          // Масштабный фактор пирамиды
    int orb_n_levels = 4;                   // Количество уровней пирамиды
    int orb_edge_threshold = 20;            // Размер бордюра
    int orb_first_level = 0;                // Первый уровень пирамиды
    int orb_wta_k = 2;                      // Параметр WTA_K
    int orb_score_type = 1;                 // Тип оценки (HARRIS)
    int orb_patch_size = 31;                // Размер патча
    int orb_fast_threshold = 20;            // Порог FAST детектора

    // Параметры FLANN матчера
    int flann_search_params = 10;           // Параметры поиска FLANN

    // Параметры фильтрации совпадений
    double good_match_ratio = 0.65;         // Соотношение для Lowe's ratio test
    int min_good_matches = 5;               // Минимальное количество хороших совпадений

    // Параметры гомографии
    double ransac_threshold = 3.0;          // Порог RANSAC

    // Флаги управления системой
    bool save_snapshots = false;            // Сохранять ли снэпшоты для отладки
};

// =============================================================================
// СТРУКТУРА КОНТЕКСТА ОБРАБОТКИ ИЗОБРАЖЕНИЙ
// =============================================================================
// Содержит все данные, необходимые для обработки изображений, и обеспечивает
// безопасный обмен данными между потоками
struct AngleContext {
    // Мьютекс для защиты общих данных от состояний гонки (race conditions)
    std::mutex data_mutex;

    // =========================================================================
    // ДАННЫЕ ТЕКУЩЕГО КАДРА
    // =========================================================================
    cv::Mat latest_frame;           // Последний захваченный кадр с камеры
    bool new_frame_available = false; // Флаг наличия нового кадра для обработки
    std::string latest_snapshot_name; // Имя снэпшота для последнего кадра

    // =========================================================================
    // ВРЕМЕННЫЕ МЕТКИ ДЛЯ ИЗМЕРЕНИЙ
    // =========================================================================
    std::chrono::high_resolution_clock::time_point capture_start_time{};
    std::chrono::high_resolution_clock::time_point capture_end_time{};
    std::chrono::high_resolution_clock::time_point processing_start_time{};
    std::chrono::high_resolution_clock::time_point processing_end_time{};

    // =========================================================================
    // ДАННЫЕ РЕФЕРЕНСНОГО ИЗОБРАЖЕНИЯ
    // =========================================================================
    cv::Mat ref_image;              // Исходное референсное изображение (цветное)
    cv::Mat ref_gray;               // Референсное изображение в оттенках серого
    std::vector<cv::KeyPoint> kp_ref; // Ключевые точки референсного изображения
    cv::Mat des_ref;                // Дескрипторы ключевых точек референса

    // =========================================================================
    // АЛГОРИТМЫ ОБРАБОТКИ ИЗОБРАЖЕНИЙ
    // =========================================================================
    cv::Ptr<cv::ORB> orb;           // Детектор и дескриптор ORB для поиска особенностей
    cv::Ptr<cv::FlannBasedMatcher> flann; // Матчер для сравнения дескрипторов

    // =========================================================================
    // КОНФИГУРАЦИЯ ОБРАБОТКИ ИЗОБРАЖЕНИЙ
    // =========================================================================
    ImageProcessingConfig config;   // Параметры обработки изображений

    // =========================================================================
    // РЕЗУЛЬТАТЫ ОБРАБОТКИ
    // =========================================================================
    double execution_time = 0;      // Время выполнения обработки в миллисекундах
    double capture_time = 0;        // Время выполнения захвата в миллисекундах
    double total_time = 0;          // Полное время исполнения пайплайна в миллисекундах
    int x_position = 0;             // Вычисленная X-координата объекта на изображении
    bool processing_complete = false; // Флаг завершения обработки текущего кадра

    // =========================================================================
    // ФЛАГИ УПРАВЛЕНИЯ СИСТЕМОЙ
    // =========================================================================
    bool save_snapshots = false;    // Флаг сохранения снэпшотов для отладки
    // В продакшене должен быть false для максимальной производительности
};

// =============================================================================
// ПРОТОТИПЫ ФУНКЦИЙ ДЛЯ РАБОТЫ С ИЗОБРАЖЕНИЯМИ
// =============================================================================

// Инициализирует обработку - загружает референсное изображение и настраивает алгоритмы
void initialize_angle_processing(AngleContext& context);

// Обрабатывает один кадр, вычисляет позицию и возвращает true при успехе
bool process_frame(AngleContext& context, const cv::Mat& query_image);

// Создает и возвращает умный указатель на инициализированный контекст обработки
std::unique_ptr<AngleContext> create_angle_context();

// Читает конфигурацию обработки изображений из файла
ImageProcessingConfig read_image_processing_config(const std::string& filename = "config.ini");