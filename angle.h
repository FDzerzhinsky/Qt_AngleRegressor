#pragma once

// =============================================================================
// ВКЛЮЧЕНИЕ БИБЛИОТЕК OPENCV
// =============================================================================
#include <opencv2/opencv.hpp>
#include <opencv2/dnn.hpp>

// =============================================================================
// СТАНДАРТНЫЕ БИБЛИОТЕКИ C++
// =============================================================================
#include <iostream>
#include <chrono>
#include <mutex>
#include <memory>
#include <vector>
#include <string>
#include <fstream>
#include <sstream>

// =============================================================================
// СТРУКТУРА КОНФИГУРАЦИИ НЕЙРОСЕТЕВОЙ МОДЕЛИ
// =============================================================================
// Содержит все настраиваемые параметры для нейросетевой модели
struct NeuralNetworkConfig {
    // Параметры путей и файлов
    std::string model_path = "can_angle_model.onnx";  // Путь к ONNX модели

    // Параметры входного изображения
    cv::Size input_size = cv::Size(536, 256);         // Размер входного изображения (width, height)
    int input_channels = 1;                            // Количество каналов (1 для grayscale)

    // Параметры нормализации
    float mean = 0.485f;                              // Среднее для нормализации
    float std = 0.229f;                               // Стандартное отклонение
    float scale_factor = 1.0f / 255.0f;               // Масштабирование пикселей

    // Параметры модели
    int num_classes = 360;                            // Количество классов (углов)
    bool use_gpu = false;                             // Использовать ли GPU (если доступно)
};

// =============================================================================
// СТРУКТУРА КОНТЕКСТА ОБРАБОТКИ ИЗОБРАЖЕНИЙ (НЕЙРОСЕТЕВАЯ ВЕРСИЯ)
// =============================================================================
// Содержит все данные, необходимые для обработки изображений нейросетью, и обеспечивает
// безопасный обмен данными между потоками
struct AngleContext {
    // Мьютекс для защиты общих данных от состояний гонки (race conditions)
    std::mutex data_mutex;

    // =========================================================================
    // ДАННЫЕ ТЕКУЩЕГО КАДРА
    // =========================================================================
    cv::Mat latest_frame;           // Последний захваченный кадр с камеры (BGR)
    cv::Mat processed_frame;        // Предобработанный кадр для нейросети (Grayscale)
    bool new_frame_available = false; // Флаг наличия нового кадра для обработки
    std::string latest_snapshot_name; // Имя снэпшота для последнего кадра

    // =========================================================================
    // НЕЙРОСЕТЕВЫЕ КОМПОНЕНТЫ
    // =========================================================================
    cv::dnn::Net neural_net;        // Нейросетевая модель OpenCV DNN
    NeuralNetworkConfig nn_config;  // Конфигурация нейросети
    bool model_loaded = false;      // Флаг успешной загрузки модели

    // =========================================================================
    // ВРЕМЕННЫЕ МЕТКИ ДЛЯ ИЗМЕРЕНИЙ
    // =========================================================================
    std::chrono::high_resolution_clock::time_point capture_start_time{};
    std::chrono::high_resolution_clock::time_point capture_end_time{};
    std::chrono::high_resolution_clock::time_point processing_start_time{};
    std::chrono::high_resolution_clock::time_point processing_end_time{};

    // =========================================================================
    // РЕЗУЛЬТАТЫ ОБРАБОТКИ
    // =========================================================================
    double execution_time = 0;      // Время выполнения обработки в миллисекундах
    double capture_time = 0;        // Время выполнения захвата в миллисекундах
    double total_time = 0;          // Полное время исполнения пайплайна в миллисекундах
    int predicted_angle = 0;        // Предсказанный угол (0-359 градусов)
    float confidence = 0.0f;        // Уверенность предсказания (0-1)
    bool processing_complete = false; // Флаг завершения обработки текущего кадра

    // =========================================================================
    // ФЛАГИ УПРАВЛЕНИЯ СИСТЕМОЙ
    // =========================================================================
    bool save_snapshots = false;    // Флаг сохранения снэпшотов для отладки
};

// =============================================================================
// ПРОТОТИПЫ ФУНКЦИЙ ДЛЯ РАБОТЫ С НЕЙРОСЕТЕВОЙ МОДЕЛЬЮ
// =============================================================================

// Инициализирует обработку - загружает нейросетевую модель и настраивает параметры
void initialize_angle_processing(AngleContext& context);

// Обрабатывает один кадр, определяет угол и возвращает true при успехе
bool process_frame(AngleContext& context, const cv::Mat& query_image);

// Создает и возвращает умный указатель на инициализированный контекст обработки
std::unique_ptr<AngleContext> create_angle_context();

// Читает конфигурацию обработки изображений из файла
NeuralNetworkConfig read_neural_network_config(const std::string& filename = "config.ini");

// Вспомогательная функция для предобработки изображения перед подачей в нейросеть
cv::Mat preprocess_frame_for_nn(const cv::Mat& input_frame, const NeuralNetworkConfig& config);